"""Generated scenarios must be indistinguishable from hand-written ones, so the
central assertion here is: whatever the generator writes passes the same validation
the hand-written scenarios pass."""

from __future__ import annotations

import pytest

from ontrak.generator import GenerationError, generate, generate_matrix, primitive_matrix
from ontrak.primitives import PRIMITIVES, by_category, get, list_all
from ontrak.scenarios import ScenarioRepository


@pytest.fixture()
def repository(tmp_path) -> ScenarioRepository:
    root = tmp_path / "scenarios"
    root.mkdir()
    return ScenarioRepository(root)


