def test_primitives_cover_every_family():
    groups = by_category()
    assert {"hardware", "software", "network", "os", "security"} <= set(groups)


def test_every_primitive_has_a_reversible_setup_and_a_live_check():
    for primitive in list_all():
        assert primitive.briefing.strip(), primitive.id
        assert primitive.objectives, primitive.id
        assert primitive.check_ps.strip(), primitive.id
        assert primitive.setup_ps.strip(), primitive.id
        assert any(o.critical for o in primitive.objectives), (
            f"{primitive.id} has no critical objective; a scenario should have at "
            "least one thing the student must not miss"
        )
        # The check must reference each objective by the same id, or it would
        # silently score zero forever.
        for objective in primitive.objectives:
            assert f"'{objective.id}'" in primitive.check_ps, (primitive.id, objective.id)


def test_primitive_ids_are_unique():
    assert len(set(PRIMITIVES)) == len(PRIMITIVES)


def test_unknown_primitive_raises_with_the_available_list():
    with pytest.raises(KeyError, match="unknown fault primitive"):
        get("make-it-broken")


