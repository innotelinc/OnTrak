def test_matrix_generates_a_valid_scenario_for_every_primitive(repository):
    results = generate_matrix(repository, prefix="gen")
    assert len(results) == len(list_all())
    problems = [p for result in results for p in result.problems]
    assert problems == [], problems
    # Every generated scenario is visible to the repository afterwards.
    ids = set(repository.ids())
    assert {r.scenario_id for r in results} <= ids


def test_matrix_is_repeatable(repository):
    first = generate_matrix(repository, prefix="gen")
    second = generate_matrix(repository, prefix="gen", force=True)
    assert [r.scenario_id for r in first] == [r.scenario_id for r in second]
    assert [r.objective_ids for r in first] == [r.objective_ids for r in second]


def test_primitive_matrix_description_is_usable_by_the_cli():
    matrix = primitive_matrix()
    assert matrix["count"] == len(PRIMITIVES)
    assert set(matrix["categories"]) == {"hardware", "software", "network", "os", "security"}
    for row in matrix["primitives"]:
        assert row["objectives"]
        assert row["minutes"] > 0
    for combo in matrix["combinations"]:
        assert len(combo["primitives"]) >= 2
        assert combo["scenario_id"]


def test_combination_suggestions_only_name_real_primitives():
    matrix = primitive_matrix()
    for combo in matrix["combinations"]:
        for primitive_id in combo["primitives"]:
            assert primitive_id in PRIMITIVES
